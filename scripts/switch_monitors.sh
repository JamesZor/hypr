#!/usr/bin/env bash

# Directory of monitor profiles
PROFILES_DIR="$HOME/.config/hypr/hyprland/profiles"
MONITORS_CONF="$HOME/.config/hypr/hyprland/monitors.conf"
HYPRPAPER_CONF="$HOME/.config/hypr/hyprpaper.conf"
WALLPAPERS_DIR="$HOME/.config/hypr/wallpapers"

# Function to generate dynamic hyprpaper.conf with random wallpapers for a profile
randomize_wallpapers() {
    local profile_path="$1"
    if [ ! -f "$profile_path" ]; then
        return 1
    fi

    # Find active monitors in the profile (exclude disabled ones)
    mapfile -t monitors < <(grep '^monitor[[:space:]]*=' "$profile_path" | grep -v 'disable' | cut -d'=' -f2- | cut -d',' -f1 | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')

    if [ ${#monitors[@]} -eq 0 ]; then
        return 0
    fi

    # Find all image files in the wallpapers directory (jpg, jpeg, png)
    local images=()
    while IFS= read -r -d '' file; do
        images+=("$file")
    done < <(find "$WALLPAPERS_DIR" -maxdepth 1 -type f \( -iname "*.jpg" -o -iname "*.jpeg" -o -iname "*.png" \) -print0)

    if [ ${#images[@]} -eq 0 ]; then
        if command -v notify-send >/dev/null 2>&1; then
            notify-send "Wallpaper Randomizer" "No wallpapers found in $WALLPAPERS_DIR" -u critical
        fi
        return 1
    fi

    # Monitor resolutions from the profile (e.g. "3440x1440"), keyed by monitor
    declare -A monitor_res
    while IFS=',' read -r name mode _; do
        name=$(echo "$name" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
        monitor_res["$name"]=$(echo "$mode" | sed 's/^[[:space:]]*//;s/@.*//')
    done < <(grep '^monitor[[:space:]]*=' "$profile_path" | grep -v 'disable' | cut -d'=' -f2-)

    # Randomly assign a wallpaper to each active monitor
    declare -A preloads
    declare -A monitor_wallpapers
    declare -A monitor_fit

    for monitor in "${monitors[@]}"; do
        local rand_idx=$(( RANDOM % ${#images[@]} ))
        local selected_img="${images[$rand_idx]}"
        monitor_wallpapers["$monitor"]="$selected_img"
        preloads["$selected_img"]=1

        # Images smaller than the monitor are letterboxed (contain) instead of
        # stretched and cropped (fill)
        monitor_fit["$monitor"]="fill"
        local res="${monitor_res[$monitor]}"
        local img_size
        img_size=$(identify -format '%w %h' "${selected_img}[0]" 2>/dev/null)
        if [[ "$res" =~ ^([0-9]+)x([0-9]+)$ && -n "$img_size" ]]; then
            local mon_w=${BASH_REMATCH[1]} mon_h=${BASH_REMATCH[2]}
            read -r img_w img_h <<< "$img_size"
            if (( img_w < mon_w || img_h < mon_h )); then
                monitor_fit["$monitor"]="contain"
            fi
        fi
    done

    # Remove symlink if exists to avoid overwriting profile templates
    rm -f "$HYPRPAPER_CONF"

    # Generate fresh hyprpaper.conf
    {
        echo "# Dynamically generated by switch_monitors.sh"
        echo "# Active layout profile: $(basename "$profile_path")"
        echo ""
        
        # Write preloads
        for img in "${!preloads[@]}"; do
            echo "preload = $img"
        done
        echo ""

        # Write monitor wallpaper blocks
        for monitor in "${!monitor_wallpapers[@]}"; do
            echo "wallpaper {"
            echo "    monitor = $monitor"
            echo "    path = ${monitor_wallpapers[$monitor]}"
            echo "    fit_mode = ${monitor_fit[$monitor]}"
            echo "}"
        done
        echo ""
        echo "splash = false"
        echo "ipc = on"
    } > "$HYPRPAPER_CONF"

    # Restart hyprpaper to apply new wallpapers
    pkill hyprpaper
    sleep 0.2
    hyprpaper >/dev/null 2>&1 &
}

# Ensure each active monitor is on its bound workspace range (<id>01..<id>10)
# and migrate any windows stranded on fallback workspaces (e.g. 11, 13)
normalize_workspaces() {
    local focused_mon
    focused_mon=$(hyprctl monitors -j | jq -r '.[] | select(.focused==true).name // empty')

    while read -r mon_json; do
        local mon_id mon_name active_ws min_ws max_ws default_ws
        mon_id=$(echo "$mon_json" | jq -r '.id')
        mon_name=$(echo "$mon_json" | jq -r '.name')
        active_ws=$(echo "$mon_json" | jq -r '.activeWorkspace.id')

        min_ws=$(( mon_id * 100 + 1 ))
        max_ws=$(( mon_id * 100 + 10 ))
        default_ws=$min_ws

        if (( active_ws < min_ws || active_ws > max_ws )); then
            # Move any windows from the unbound fallback workspace onto default_ws
            while read -r addr; do
                [ -n "$addr" ] && hyprctl dispatch movetoworkspacesilent "$default_ws,address:$addr" >/dev/null
            done < <(hyprctl clients -j | jq -r ".[] | select(.workspace.id == $active_ws) | .address")

            hyprctl dispatch focusmonitor "$mon_name" >/dev/null
            hyprctl dispatch workspace "$default_ws" >/dev/null
        fi
    done < <(hyprctl monitors -j | jq -c '.[]')

    [ -n "$focused_mon" ] && hyprctl dispatch focusmonitor "$focused_mon" >/dev/null
}

# --- Main Logic ---

# Check if we just want to randomize the current profile (e.g. on boot)
if [ "$1" = "--randomize" ]; then
    # Detect the active profile from the monitors.conf symlink
    if [ -L "$MONITORS_CONF" ]; then
        ACTIVE_PROFILE=$(readlink -f "$MONITORS_CONF")
        if [ -f "$ACTIVE_PROFILE" ]; then
            randomize_wallpapers "$ACTIVE_PROFILE"
            exit 0
        fi
    fi
    exit 1
fi

# Otherwise, run Rofi menu
OPTIONS="Laptop\nHome\nOffice\nMain\nPi_screen"
SELECTED=$(echo -e "$OPTIONS" | rofi -dmenu -p "Select Monitor Layout" -i)

if [ -z "$SELECTED" ]; then
    exit 0
fi

PROFILE_FILE=$(echo "$SELECTED" | tr '[:upper:]' '[:lower:]').conf
PROFILE_PATH="$PROFILES_DIR/$PROFILE_FILE"

if [ -f "$PROFILE_PATH" ]; then
    # Symlink the display layout
    ln -sf "$PROFILE_PATH" "$MONITORS_CONF"
    
    # Reload Hyprland
    hyprctl reload

    # Ensure all monitors switch off fallback workspaces (e.g. 11, 13) onto their profile workspaces
    normalize_workspaces
    
    # Randomize and set wallpapers for this layout
    randomize_wallpapers "$PROFILE_PATH"
    
    # Notification
    if command -v notify-send >/dev/null 2>&1; then
        notify-send "Monitor Switcher" "Switched to '$SELECTED' layout with random wallpapers" -i video-display -t 2000
    fi
else
    if command -v notify-send >/dev/null 2>&1; then
        notify-send "Monitor Switcher" "Error: Profile file '$PROFILE_FILE' not found!" -u critical -i dialog-error
    fi
fi
