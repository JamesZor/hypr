#!/usr/bin/env bash

# Per-workspace tiling layout switcher (super+t)
# Shows a rofi menu with an ASCII diagram of each layout, applies the choice
# live to the focused workspace and remembers it for the active monitor profile.

ACTIVE_PROFILE_FILE="$HOME/.config/hypr/lua/state/active_profile.lua"
STATE_DIR="$HOME/.config/hypr/lua/state/layouts"

MODES=(master_center master_1920 scrolling gamebox dwindle)

declare -A NAME DIAGRAM
NAME[master_center]="Centred master"
DIAGRAM[master_center]="\
┌──────┬──────────────┬──────┐
│ s1   │              │ s2   │
├──────┤    master    │      │
│ s3   │     55%      ├──────┤
└──────┴──────────────┴──────┘"

NAME[master_1920]="Centre master 1920px"
DIAGRAM[master_1920]="\
┌─────┬────────────────┬─────┐
│ s1  │                │ s2  │
├─────┤ centre  1920px │     │
│ s3  │  full height   ├─────┤
└─────┴────────────────┴─────┘"

NAME[scrolling]="Scrolling (niri style)"
DIAGRAM[scrolling]="\
  ┌────────┬────────┬────────┐
◀ │ col 1  │ col 2  │ col 3  │ ▶
  │        ├────────┤        │
  │        │ col 2b │        │
  └────────┴────────┴────────┘"

NAME[gamebox]="Game box 1920x1080"
DIAGRAM[gamebox]="\
┌────────────────────────────┐
│     ┌────────────────┐     │
│     │   1920x1080    │     │
│     └────────────────┘     │
└────────────────────────────┘"

NAME[dwindle]="Dwindle (default)"
DIAGRAM[dwindle]="\
┌──────────────┬─────────────┐
│              │     w2      │
│      w1      ├──────┬──────┤
│              │  w3  │  w4  │
└──────────────┴──────┴──────┘"

# --- Focused workspace / monitor ---
monitor_json=$(hyprctl -j monitors | jq -c '.[] | select(.focused==true)')
ws=$(echo "$monitor_json" | jq -r '.activeWorkspace.id')
mon_name=$(echo "$monitor_json" | jq -r '.name')

if ! [[ "$ws" =~ ^[0-9]+$ ]]; then
    notify-send "Layout Switcher" "Can't set a layout on workspace '$ws'" -u critical
    exit 1
fi

# State file for the active monitor profile (applied by lua/modules/workspaces.lua)
profile=$(lua - "$ACTIVE_PROFILE_FILE" 2>/dev/null <<'LUA'
local n = dofile(arg[1]); if type(n) == "string" then print(n) end
LUA
)
if ! [[ "$profile" =~ ^[A-Za-z0-9_]+$ ]]; then
    notify-send "Layout Switcher" "Can't read the active profile from $ACTIVE_PROFILE_FILE" -u critical
    exit 1
fi
STATE_FILE="$STATE_DIR/$profile.lua"
mkdir -p "$STATE_DIR"
[ -f "$STATE_FILE" ] || printf -- '-- Generated by switch_layout.sh - per-workspace layouts for the %s profile\nreturn {\n}\n' "$profile" > "$STATE_FILE"

# --- Current mode (from the state file, else from the live layout) ---
current=$(lua - "$STATE_FILE" "$ws" <<'LUA' | tail -n1
    local ok, t = pcall(dofile, arg[1])
    for _, e in ipairs((ok and type(t) == "table") and t or {}) do
        if type(e) == "table" and type(e.rule) == "table" and tostring(e.rule.workspace) == arg[2] then
            print(e.mode or "")
        end
    end
LUA
)
if [ -z "$current" ]; then
    case $(hyprctl -j workspaces | jq -r ".[] | select(.id==$ws) | .tiledLayout") in
        master) current=master_center ;;
        scrolling) current=scrolling ;;
        monocle) current=gamebox ;;
        *) current=dwindle ;;
    esac
fi

# --- Rofi menu: each entry is a title line plus its diagram ---
entries=""
selected_row=0
for i in "${!MODES[@]}"; do
    mode=${MODES[$i]}
    marker="  "
    if [ "$mode" = "$current" ]; then
        marker="● "
        selected_row=$i
    fi
    entries+="${marker}${NAME[$mode]}"$'\n'"${DIAGRAM[$mode]}|"
done

# A mode can be passed directly (e.g. `switch_layout.sh gamebox`) to skip the menu
if [ -n "$1" ]; then
    mode=$1
    if [ -z "${NAME[$mode]}" ]; then
        echo "Unknown mode '$mode' (valid: ${MODES[*]})" >&2
        exit 1
    fi
else
    choice=$(printf '%s' "${entries%|}" | rofi -dmenu -i -no-custom -format i \
        -sep '|' -eh 6 -selected-row "$selected_row" \
        -p "Layout" -mesg "Workspace $ws on $mon_name" \
        -theme-str '* { font: "IBM Plex Mono 11"; } window { width: 24em; } listview { lines: 5; }')

    [ -z "$choice" ] && exit 0
    mode=${MODES[$choice]}
fi

# --- Build the workspace rule for the chosen mode ---
gaps_in=$(hyprctl -j getoption general:gaps_in | jq -r '.css')
border_size=$(hyprctl -j getoption general:border_size | jq -r '.int')
default_mfact=$(hyprctl -j getoption master:mfact | jq -r '.float')

# Usable monitor area in logical pixels (minus reserved space, e.g. bars)
read -r mon_w mon_h <<< "$(echo "$monitor_json" | jq -r '
    "\((.width / .scale - .reserved[0] - .reserved[2]) | floor) \((.height / .scale - .reserved[1] - .reserved[3]) | floor)"')"

# Workspace rule for the mode; mfact is set separately (it is not a workspace rule)
mfact=""
case $mode in
    master_center)
        rule='layout = "master", layout_opts = { orientation = "center" }'
        mfact=$default_mfact
        ;;
    master_1920)
        rule='layout = "master", layout_opts = { orientation = "center" }'
        # Master width including its border and inner gaps
        mfact=$(awk -v w="$mon_w" -v b="$border_size" -v g="${gaps_in%% *}" \
            'BEGIN { m = (1920 + 2*b + 2*g) / w; if (m > 1) m = 1; printf "%.4f", m }')
        ;;
    scrolling)
        rule='layout = "scrolling"'
        ;;
    gamebox)
        gap_x=$(( (mon_w - 1920) / 2 )); (( gap_x < 0 )) && gap_x=0
        gap_y=$(( (mon_h - 1080) / 2 )); (( gap_y < 0 )) && gap_y=0
        rule="layout = \"monocle\", gaps_out = { top = $gap_y, right = $gap_x, bottom = $gap_y, left = $gap_x }, gaps_in = 0, border_size = 0, no_rounding = true"
        ;;
    dwindle)
        rule='layout = "dwindle"'
        ;;
esac

# --- Persist for this profile and apply ---
# Written in one atomic step: the state file is read on every config reload and
# must never be seen half-written. Entries for other workspaces are kept as-is.
tmp=$(mktemp "$STATE_DIR/.$profile.XXXXXX")
if ! lua - "$STATE_FILE" "$ws" "$mode" "$rule" "$profile" > "$tmp" <<'LUA'
    local path, ws, mode, rule, profile = arg[1], arg[2], arg[3], arg[4], arg[5]
    local ok, old = pcall(dofile, path)
    if not ok or type(old) ~= "table" then old = {} end
    local function q(s) return string.format("%q", tostring(s)) end
    local function ser(v)
        if type(v) == "string" then return q(v) end
        if type(v) ~= "table" then return tostring(v) end
        local keys = {}
        for k in pairs(v) do keys[#keys + 1] = k end
        table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
        local parts = {}
        for _, k in ipairs(keys) do parts[#parts + 1] = tostring(k) .. " = " .. ser(v[k]) end
        return "{ " .. table.concat(parts, ", ") .. " }"
    end
    local out = { "-- Generated by switch_layout.sh - per-workspace layouts for the " .. profile .. " profile", "return {" }
    for _, e in ipairs(old) do
        if type(e) == "table" and type(e.rule) == "table" and tostring(e.rule.workspace) ~= ws then
            out[#out + 1] = "  { mode = " .. q(e.mode) .. ", rule = " .. ser(e.rule) .. " },"
        end
    end
    out[#out + 1] = "  { mode = " .. q(mode) .. ", rule = { workspace = " .. q(ws) .. ", " .. rule .. " } },"
    out[#out + 1] = "}"
    io.write(table.concat(out, "\n"), "\n")
LUA
then
    rm -f "$tmp"
    notify-send "Layout Switcher" "Failed to write $STATE_FILE" -u critical
    exit 1
fi
mv "$tmp" "$STATE_FILE"

# Reload rebuilds all workspace rules from the files, which also clears any
# gaps/border overrides left by the previous mode
hyprctl reload >/dev/null
[ -n "$mfact" ] && hyprctl eval "hl.dispatch(hl.dsp.layout('mfact exact $mfact'))" >/dev/null

if command -v notify-send >/dev/null 2>&1; then
    notify-send "Layout Switcher" "Workspace $ws: ${NAME[$mode]}" -i view-grid -t 2000 2>/dev/null
fi
